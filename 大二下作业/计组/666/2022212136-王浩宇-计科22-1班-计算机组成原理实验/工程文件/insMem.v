`timescale 1ns / 1ps
//////////////////////////////////////////////////////////////////////////////////
// 指令存储器模块，用于存储和输出指令
//////////////////////////////////////////////////////////////////////////////////
module insMem(
    input wire [11:0] addr,         // 地址，来自程序计数器
    output wire [15:0] Ins          // 输出的指令
);
    // 4K×16位的指令存储器
    reg[15:0] insMem[4095:0];
    
    // 初始化指令内存，存放测试程序
    initial begin
        // 操作码定义:
        // 0000: CLA (清除累加器)
        // 0001: COM (累加器取反)
        // 0010: SHR (算术右移一位)
        // 0011: CSL (循环左移一位)
        // 0100: ADD (加法指令)
        // 0101: STA (存数指令)
        // 0110: LDA (取数指令)
        // 0111: JMP (无条件转移)
        // 1000: BAN (负则转)
        // 1001: STP (停机)
        
        // 测试程序：依次测试所有指令
        insMem[0] = 16'b0000000000000000;  // CLA: 清除累加器
        insMem[1] = 16'b0110000001100100;  // LDA 100: 从地址100加载数据(0x1234)
        insMem[2] = 16'b0100000001100101;  // ADD 101: 加上地址101的值(0x5678)
        insMem[3] = 16'b0101000001100110;  // STA 102: 存储结果到地址102
        insMem[4] = 16'b0001000000000000;  // COM: 累加器取反
        insMem[5] = 16'b0010000000000000;  // SHR: 算术右移一位
        insMem[6] = 16'b0011000000000000;  // CSL: 循环左移一位
        insMem[7] = 16'b0111000000001010;  // JMP 10: 跳转到地址10
        insMem[8] = 16'b1001000000000000;  // STP: 停机（不会执行到）
        insMem[9] = 16'b1001000000000000;  // STP: 停机（不会执行到）
        insMem[10] = 16'b0110000001101010; // LDA 106: 加载负数(0x8000)
        insMem[11] = 16'b1000000000000010; // BAN 2: 如果ACC为负，PC+2
        insMem[12] = 16'b0111000000001110; // JMP 14: 跳转到地址14
        insMem[13] = 16'b1001000000000000; // STP: 停机（不会执行到）
        insMem[14] = 16'b1001000000000000; // STP: 停机
    end
    
    // 输出当前地址的指令
    assign Ins = insMem[addr];
endmodule 